import { appendFileSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Only public configuration is written. The private updater key stays in the build environment.
const env = process.env;
const publicKey = env.ODC_UPDATER_PUBLIC_KEY?.trim() ?? '';
const privateKey = env.TAURI_SIGNING_PRIVATE_KEY?.trim() ?? '';
const requireUpdaterSigning = env.ODC_REQUIRE_SIGNING === 'true';
const fail = (message) => {
  throw new Error(`Release configuration: ${message}`);
};
if (env.ODC_REQUIRE_SIGNING && !['true', 'false'].includes(env.ODC_REQUIRE_SIGNING))
  fail('ODC_REQUIRE_SIGNING must be true or false.');
if (!!publicKey !== !!privateKey)
  fail('set both ODC_UPDATER_PUBLIC_KEY and TAURI_SIGNING_PRIVATE_KEY, or neither.');
if (requireUpdaterSigning && !publicKey) fail('signed updates require updater keys.');
if (publicKey) {
  const lines = Buffer.from(publicKey, 'base64').toString('utf8').trim().split(/\r?\n/);
  const key = Buffer.from(lines[1] ?? '', 'base64');
  if (
    !lines[0]?.startsWith('untrusted comment:') ||
    lines.length !== 2 ||
    key.length !== 42 ||
    key.subarray(0, 2).toString() !== 'Ed'
  )
    fail(
      'ODC_UPDATER_PUBLIC_KEY must contain the public .pub file generated by the Tauri signer (not a path).',
    );
}
const repository = env.GITHUB_REPOSITORY ?? 'hoxsec/opendronecinematic';
if (!/^[\w.-]+\/[\w.-]+$/.test(repository)) fail('invalid release repository.');
const config = {
  bundle: {
    createUpdaterArtifacts: !!publicKey,
    // Ad-hoc signing supports Apple Silicon without a paid identity or notarization.
    // It does NOT establish publisher trust or remove Gatekeeper warnings.
    macOS: { signingIdentity: '-' },
  },
  plugins: {
    updater: {
      pubkey: publicKey,
      endpoints: publicKey
        ? [`https://github.com/${repository}/releases/latest/download/latest.json`]
        : [],
      windows: { installMode: 'passive' },
    },
  },
};
if (env.GITHUB_REF_TYPE === 'tag') {
  const app = JSON.parse(
    readFileSync(new URL('../src-tauri/tauri.conf.json', import.meta.url), 'utf8'),
  );
  if (env.GITHUB_REF_NAME !== `v${app.version}`)
    fail('the release tag must match tauri.conf.json version.');
}
const outputArg = process.argv.indexOf('--output');
const output =
  outputArg >= 0
    ? process.argv[outputArg + 1]
    : fileURLToPath(new URL('../src-tauri/tauri.release.conf.json', import.meta.url));
if (!output) fail('--output requires a path.');
writeFileSync(output, `${JSON.stringify(config, null, 2)}\n`);
if (env.GITHUB_OUTPUT) appendFileSync(env.GITHUB_OUTPUT, `updater-enabled=${!!publicKey}\n`);
console.log(
  publicKey
    ? 'Signed updater artifacts enabled; no Windows publisher signing or Apple notarization.'
    : 'Updater disabled: manual-update build with no publisher signing.',
);
